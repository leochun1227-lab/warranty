import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';

const out = path.dirname(fileURLToPath(import.meta.url));
const input = path.resolve(out, '../recall_postcode_20260914');
const results = JSON.parse(await fs.readFile(path.join(input, 'match_results.json'), 'utf8'));
const tickets = JSON.parse(await fs.readFile(path.join(input, 'firebase_before.json'), 'utf8')).tickets;
const conflicts = results.filter(r => r.status === 'conflicting_postcodes');
if (conflicts.length !== 38) throw new Error('Expected 38 conflicts.');
const regFile = 'Product_Registrations_Till_17072026.xlsx';
const sapFile = 'SAPAnalyticsReport(Z578DB6F34E1CDB92C9D1CE).xlsx';
const customerDifferences = new Set(['39596', '40568', '40641', '40649', '40704', '40739', '40773', '41354', '41411', '41446']);
const rows = conflicts.map(r => {
  const t = tickets[r.ticket_id];
  const serial = t.product?.serialId || t.ticket?.SerialID || '';
  let customer = t.ticket?.TicketName || '';
  if (serial && customer.toUpperCase().endsWith(serial.toUpperCase())) customer = customer.slice(0, -serial.length).trim();
  const codes = source => [...new Set(r.evidence.filter(e => e.source === source && e.postcode).map(e => e.postcode))].sort();
  const reg = codes(regFile), sap = codes(sapFile);
  if (codes('VCUST.XLSX').length) throw new Error('VCUST conflict evidence needs its own column.');
  const shown = [...new Set([...reg, ...sap])].sort();
  if (JSON.stringify(shown) !== JSON.stringify(r.candidate_postcodes)) throw new Error('Postcode evidence mismatch.');
  const note = customerDifferences.has(r.ticket_id) ? 'Customer names and postcodes differ.' : reg.length > 1 ? 'Registration lists multiple postcodes.' : 'Postcodes differ between sources.';
  return [r.ticket_id, customer, serial, reg.join(' / '), sap.join(' / '), note];
});

const wb = Workbook.create();
const sheet = wb.worksheets.add('Postcode conflicts');
sheet.showGridLines = false;
sheet.getRange('A1:F50').format.font = { name: 'Arial', size: 10, color: '#222222' };
sheet.getRange('A1:F50').format.verticalAlignment = 'center';
sheet.getRange('A1:F50').format.rowHeight = 21;
sheet.getRange('A2').values = [['Recall claim postcode conflicts']];
sheet.getRange('A2').format.font = { name: 'Arial', size: 12, bold: true, color: '#222222' };
sheet.getRange('A3').values = [['38 tickets require review. These postcodes were not written to Firebase.']];
sheet.getRange('A5:F5').values = [['Ticket ID', 'Customer on ticket', 'Serial ID', 'Registration postcode', 'SAP postcode', 'Explanation']];
sheet.getRange('A6:F43').values = rows;
sheet.getRange('A5:F5').format.fill = '#EEEEEE';
sheet.getRange('A5:F5').format.font = { name: 'Arial', size: 10, bold: true, color: '#222222' };
sheet.getRange('A5:F5').format.horizontalAlignment = 'center';
sheet.getRange('A5:F5').format.rowHeight = 29;
sheet.getRange('A5:F5').format.borders = { bottom: { style: 'thin', color: '#AAAAAA' } };
sheet.getRange('A6:F43').format.borders = { insideHorizontal: { style: 'thin', color: '#E8E8E8' } };
sheet.getRange('A6:F43').format.rowHeight = 26;
sheet.getRange('A6:A43').setNumberFormat('@');
sheet.getRange('C6:E43').setNumberFormat('@');
sheet.getRange('A6:A43').format.horizontalAlignment = 'left';
sheet.getRange('D6:E43').format.horizontalAlignment = 'center';
sheet.getRange('B6:B43').format.wrapText = true;
sheet.getRange('F6:F43').format.wrapText = false;
const widths = { A: 11, B: 33, C: 16, D: 23, E: 16, F: 43 };
for (const [col, width] of Object.entries(widths)) sheet.getRange(`${col}1:${col}50`).format.columnWidth = width;
for (let i = 0; i < rows.length; i++) if (rows[i][1].length > 34) sheet.getRange(`A${i+6}:F${i+6}`).format.rowHeight = 32;
sheet.getRange('A45').values = [['Sources']];
sheet.getRange('A45').format.font.bold = true;
sheet.getRange('A46').values = [[`Registration: ${regFile} | Sheet38 | Postcode: column N`]];
sheet.getRange('A47').values = [[`SAP: ${sapFile} | First sheet | Postal Code: column T`]];
sheet.getRange('A48').values = [['VCUST.XLSX provided no additional matched postcode for these 38 tickets.']];
sheet.getRange('A49').values = [['A slash separates multiple postcodes found in the same source. Review date: 14 Sep 2026.']];
sheet.freezePanes.freezeRows(5);
wb.recalculate();
console.log((await wb.inspect({kind:'table',range:"'Postcode conflicts'!A5:F10",tableMaxRows:6,tableMaxCols:6,maxChars:2400})).ndjson);
console.log((await wb.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#N/A|#NUM!|#NULL!',options:{useRegex:true,maxResults:10},maxChars:1000})).ndjson);
const png = await wb.render({sheetName:sheet.name,range:'A1:F50',scale:1.5,format:'png'});
await fs.writeFile(path.join(out, 'preview.png'),new Uint8Array(await png.arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(wb)).save(path.join(out, 'Recall_Postcode_Conflicts.xlsx'));
await fs.writeFile(path.join(out, 'expected_rows.json'),JSON.stringify(rows));
console.log(JSON.stringify({rows:rows.length,file:path.join(out,'Recall_Postcode_Conflicts.xlsx')}));
