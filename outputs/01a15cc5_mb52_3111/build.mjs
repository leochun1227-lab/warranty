import fs from 'node:fs/promises';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const dir = 'C:/Users/Leo.Li/Documents/GitHub/warranty/outputs/01a15cc5_mb52_3111';
const p = JSON.parse(await fs.readFile(`${dir}/stock.json`,'utf8'));
const wb=Workbook.create();
const sheet=wb.worksheets.add('MB52');
const values=[p.headers,...p.rows];
sheet.getRangeByIndexes(0,0,values.length,p.headers.length).values=values;
sheet.getRange(`A1:Q${values.length}`).format.font={name:'Arial',size:10};
sheet.getRange(`A2:K${values.length}`).setNumberFormat('@');
sheet.getRange(`L2:Q${values.length}`).setNumberFormat(p.rows.every(r=>r.slice(11).every(Number.isInteger))?'0':'0.000');
sheet.getRange(`A1:Q${values.length}`).format.autofitColumns();
sheet.getRange('B:C').format.columnWidth=48;
sheet.getRange('F:F').format.columnWidth=34;
sheet.getRange('A1:Q1').format.wrapText=true;
sheet.getRange('A1:Q1').format.rowHeight=30;
sheet.freezePanes.freezeRows(1);
wb.recalculate();
console.log((await wb.inspect({kind:'table',range:'MB52!A1:Q4',include:'values',tableMaxCols:17,tableMaxRows:4,maxChars:2500})).ndjson);
console.log((await wb.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#NUM!',options:{useRegex:true,maxResults:20},maxChars:1000})).ndjson);
const preview=await wb.render({sheetName:'MB52',range:'A1:Q12',scale:1,format:'png'});
await fs.writeFile(`${dir}/preview.png`,new Uint8Array(await preview.arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(wb)).save(`${dir}/MB52_3111_Z_D.xlsx`);
console.log(JSON.stringify({rows:p.rows.length,output:`${dir}/MB52_3111_Z_D.xlsx`}));
